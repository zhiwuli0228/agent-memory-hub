/**
 * Bake the standalone console (ADR-0010) into a single TypeScript string.
 *
 * React 18 UMD + react-dom UMD + htm are inlined into panel.html so the
 * console renders with ZERO network requests and ZERO build steps at runtime,
 * while staying a single self-contained HTML file. The output is serialized
 * with JSON.stringify — no template-literal escape hazards (no `${`/backtick
 * surprises, and the historical `'\n'`-becomes-real-newline class of bugs is
 * structurally impossible).
 *
 * Run before `npm run build` (wired as the `bake:panel` script). The
 * generated module is committed so host bundles (esbuild) and tsc consumers
 * always embed the exact same console.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const html = readFileSync(join(here, 'panel.html'), 'utf8')
const react = readFileSync(join(here, 'vendor', 'react.production.min.js'), 'utf8')
const reactDom = readFileSync(join(here, 'vendor', 'react-dom.production.min.js'), 'utf8')
const htm = readFileSync(join(here, 'vendor', 'htm.umd.js'), 'utf8')

// Structural guards: a stray `</script` inside any vendor file would break
// the browser parser and blank the console (the 0.1.43 lesson, automated).
for (const [name, src] of [['react', react], ['react-dom', reactDom], ['htm', htm]]) {
  if (src.includes('</script')) throw new Error(`vendor ${name} contains '</script' — cannot inline`)
}

// API-surface guards: react-dom references `Ba.unstable_requestPaint` as its
// paint scheduler (minified as `Sk=Ba.unstable_requestPaint`). A truncated
// react copy that lacks that symbol renders the shell fine and then dies with
// "Sk is not a function" on the first data-driven re-render (the 0.1.46
// console-frozen-on-loading lesson, automated here).
if (!react.includes('unstable_requestPaint')) {
  throw new Error("vendor react is missing unstable_requestPaint — re-download the official 18.3.1 UMD (truncated copies break the console)")
}
if (!reactDom.includes('unstable_requestPaint')) {
  throw new Error('vendor react-dom does not reference unstable_requestPaint — version mismatch with react UMD')
}


// split/join, NOT String.replace: minified vendor code contains `$&`-style
// patterns whose special meaning in a replace() replacement string would
// corrupt the inlined content (the 0.1.44 bake lesson, guarded below).
const full = html
  .split('/*__REACT__*/').join(react)
  .split('/*__REACT_DOM__*/').join(reactDom)
  .split('/*__HTM__*/').join(htm)

if (full.includes('/*__REACT__*/') || full.includes('/*__REACT_DOM__*/') || full.includes('/*__HTM__*/')) {
  throw new Error('bake-panel: a vendor placeholder was not replaced')
}

const out = `// AUTO-GENERATED by scripts/panel/bake-panel.mjs — do not edit by hand.
// The standalone console (ADR-0010): React 18 UMD + htm inlined, zero
// network, zero build steps, single self-contained HTML. Regenerate with
// \`npm run bake:panel\` after editing scripts/panel/panel.html or vendor/.
export const PANEL_HTML: string = ${JSON.stringify(full)}
`

writeFileSync(join(here, '..', '..', 'src', 'transport', 'panel.generated.ts'), out)
console.log(`bake-panel: wrote src/transport/panel.generated.ts (${full.length} chars)`)
